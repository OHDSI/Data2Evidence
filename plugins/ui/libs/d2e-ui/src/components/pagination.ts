export interface D2ePagerState {
  lastPage: number;
  canGoBack: boolean;
  canGoForward: boolean;
}

export function pagerState(
  page: number,
  itemsPerPage: number,
  total: number,
): D2ePagerState {
  const lastPage = Math.max(1, Math.ceil(total / itemsPerPage));
  return { lastPage, canGoBack: page > 1, canGoForward: page < lastPage };
}

export function pageTarget(
  target: number,
  page: number,
  lastPage: number,
): number | null {
  if (target < 1 || target > lastPage || target === page) return null;
  return target;
}
